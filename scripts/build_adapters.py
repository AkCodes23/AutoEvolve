#!/usr/bin/env python3
"""Generate the distribution and compatibility guide from one protocol."""

import argparse
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- Generated by scripts/build_adapters.py from PROTOCOL.md; do not edit. -->\n\n"


@dataclass(frozen=True)
class Adapter:
    id: str
    product: str
    source: str
    destination: str
    format: str
    frontmatter: str
    load_mode: str
    status: str
    versions: str
    activation: str
    documentation: str


def render(root: Path) -> dict[str, str]:
    manifest = json.loads((root / "adapters/manifest.json").read_text(encoding="utf-8"))
    if manifest["schema_version"] != 1:
        raise ValueError("Unsupported manifest schema")
    adapters = [Adapter(**entry) for entry in manifest["adapters"]]
    protocol = (root / "PROTOCOL.md").read_text(encoding="utf-8")
    if f"AutoEvolve protocol v{manifest['protocol_version']}" not in protocol:
        raise ValueError("Protocol and manifest versions differ")
    outputs = {}
    rows = []
    guide = [
        "# Adapter compatibility",
        "",
        "<!-- Generated from adapters/manifest.json; do not edit. -->",
        "",
        f"Documentation checked: {manifest['documentation_checked']}.",
        "",
        "All integrations are **experimental** until a live product/version is tested.",
        "The loader paths below follow documentation; fixture tests verify file placement,",
        "not activation inside the products. Choose only the agents you use.",
        "When multiple agents share AGENTS.md, only one copy is needed.",
        "",
        "For each selected integration, test in a clean project and again with existing",
        "user instructions. Verify both are loaded, ask the agent to identify the protocol",
        "version and stopping limits, then run a small task with an independently checked",
        "acceptance condition. Record product version, date, evidence, and precedence",
        "before changing its status. Avoid loading duplicate copies into one host.",
        "",
        "| ID | Product | Distribution source | Installed entrypoint | Format | Activation |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    destinations: dict[str, str] = {}
    for adapter in adapters:
        body = adapter.frontmatter + MARKER + protocol
        if adapter.destination in destinations and destinations[adapter.destination] != body:
            raise ValueError(f"Conflicting contents for {adapter.destination}")
        destinations[adapter.destination] = body
        outputs[adapter.source] = body
        rows.append(
            "|".join((adapter.id, adapter.source, adapter.destination, adapter.load_mode, adapter.status))
        )
        guide.append(
            f"| `{adapter.id}` | {adapter.product} | [Source](../{adapter.source}) | `{adapter.destination}` | "
            f"{adapter.format} | {adapter.load_mode} |"
        )
    outputs["adapters/manifest.txt"] = "\n".join(rows) + "\n"
    for adapter in adapters:
        guide.extend(
            [
                "",
                f"## {adapter.product} (`{adapter.id}`)",
                "",
                f"Status: **{adapter.status}**. Versions: {adapter.versions}.",
                "",
                adapter.activation,
                "",
                f"[Loader documentation]({adapter.documentation})",
            ]
        )
    outputs["docs/adapters.md"] = "\n".join(guide) + "\n"
    payloads = {name: content for name, content in outputs.items() if name != "docs/adapters.md"}
    for name in ("DIRECTION.md", "JOURNAL.md", "CONSTRAINTS.md"):
        payloads[name] = (root / name).read_text(encoding="utf-8")
    outputs["checksums.txt"] = "".join(
        f"{hashlib.sha256(content.encode('utf-8')).hexdigest()}  {name}\n"
        for name, content in sorted(payloads.items())
    )
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files have drifted")
    args = parser.parse_args()
    stale = []
    for name, content in render(ROOT).items():
        path = ROOT / name
        encoded = content.encode("utf-8")
        if args.check:
            if not path.exists() or path.read_bytes() != encoded:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(encoded)
    if stale:
        print("Regenerate with python3 scripts/build_adapters.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
